def run_multi_style_bot(
    symbol: str = "EURUSD",
    mock: bool = False,
    enable_scalp: bool = True,
    enable_intraday: bool = True,
    enable_swing: bool = True,
):
    """
    Convenience function to run multi-style bot.
    
    Args:
        symbol: Trading symbol
        mock: Use mock connector
        enable_scalp: Enable scalping strategy
        enable_intraday: Enable intraday strategy
        enable_swing: Enable swing strategy
    """
    from trading.style_config import DEFAULT_STYLE_CONFIGS
    
    # Configure styles
    configs = DEFAULT_STYLE_CONFIGS.copy()
    configs[TradingStyle.SCALP].enabled = enable_scalp
    configs[TradingStyle.INTRADAY].enabled = enable_intraday
    configs[TradingStyle.SWING].enabled = enable_swing
    
    config = OrchestratorConfig(
        symbol=symbol,
        use_mock_connector=mock,
        styles=configs,
    )
    
    orchestrator = MultiStyleOrchestrator(config)
    orchestrator.run()


